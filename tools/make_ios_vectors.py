"""Make the iPhone app's test vectors from the real Python MOSS.

The MossRadio app re-implements MOSS's wire format and encryption in Swift.
Its Self-check screen replays these exact bytes, made here by the code the
Seed Vault runs, so the phone proves it speaks MOSS bit for bit: same
sealed request, same keys derived, same capsule and spores opened, same
hashes, pings and pongs.

    python tools/make_ios_vectors.py          (from the repo root)

writes ios/MossRadio/Sources/MossRadio/TestVectors.swift. Re-run it when the
wire format changes.
"""

from __future__ import annotations

import hashlib
import os
import sys
import zlib
from pathlib import Path
from unittest import mock

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from Crypto.PublicKey import ECC                       # noqa: E402

from moss import protocol as P                         # noqa: E402
from moss import seal as S                             # noqa: E402
from moss.channel import hashtag_secret                # noqa: E402

OUT = ROOT / "ios" / "MossRadio" / "Sources" / "MossRadio" / "TestVectors.swift"

# Fixed keys: RFC 7748 / RFC 8032 test keys and two made-up ones, never used for real.
VAULT_X = bytes.fromhex("77076d0a7318a57d3c16c17251b26645df4c2f87ebc0992ab177fba51db92c2a")
VAULT_ED = bytes.fromhex("9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60")
READER_EPH = bytes.fromhex("5dab087e624a8a4b79e17f8b83800ee66f3bb1292618b6fd1c2f8b27ff88e0eb")
VAULT_EPH = bytes.fromhex("a8abababababababababababababababababababababababababababababab6b")
PADDING_BYTE = 0x5A
RID = 0x4D2B
ARTICLE = ("# Slow sand filter\n\nA **slow sand filter** cleans drinking water by passing it "
           "very slowly down through a deep bed of fine sand. [[Water purification]] covers "
           "the other ways.\n\n" + "The living layer does most of the work. " * 12).encode()
TITLE = "Slow sand filter"


def x_key(seed: bytes) -> ECC.EccKey:
    return ECC.construct(curve="curve25519", seed=seed)


def main() -> None:
    vault = S.VaultKeys(x_key(VAULT_X), ECC.construct(curve="Ed25519", seed=VAULT_ED), "Test Vault")
    hello = vault.hello()

    # The reader's sealed request, with its one-time key and padding fixed.
    with mock.patch.object(S.ECC, "generate", return_value=x_key(READER_EPH)), \
            mock.patch.object(S.os, "urandom", side_effect=lambda n: bytes([PADDING_BYTE]) * n):
        reader = S.ReaderSession(vault.x_pub, RID, P.KIND_ARTICLE, TITLE)
    request = reader.request

    # The vault opens it and answers: capsule + spores, with its one-time key fixed.
    rid, kind, query, session = vault.open_request(request)
    assert (rid, kind, query) == (RID, P.KIND_ARTICLE, TITLE)
    blob = zlib.compress(ARTICLE, 9)
    digest = P.short_hash(ARTICLE)
    with mock.patch.object(S.ECC, "generate", return_value=x_key(VAULT_EPH)):
        capsule, spores = session.seal_reply(TITLE, blob, P.FLAG_ZLIB, digest)
    chunks = [P.build_chunk(RID, i, s) for i, s in enumerate(spores)]
    error = session.error("no such article: Slow sand filtre")

    # Check the Python reader opens it all, so the vectors are right to begin with.
    m = reader.open_capsule(capsule)
    name, opened = reader.open_body(b"".join(spores), m["body_len"])
    assert name == TITLE and zlib.decompress(opened) == ARTICLE
    assert reader.open_error(error) == "no such article: Slow sand filtre"

    v = {
        "vaultXPub": vault.x_pub, "vaultEdPub": vault.ed_pub,
        "readerEphPrivate": READER_EPH,
        "hello": hello,
        "request": request,
        "capsule": capsule,
        "chunks": chunks,
        "error": error,
        "nack": P.build_nack(RID, [3, 7, 300]),
        "done": P.build_done(RID),
        "status": P.build_status(RID, P.ST_QUEUED, 2),
        "whois": bytes([S.WHOIS]) + RID.to_bytes(2, "little"),
        "ping": P.build_ping(0xBEEF, 12, P.PING_ZERO_HOP),
        "pong": P.build_pong(0xBEEF, 12, -6.75, -97, 255, P.PING_ZERO_HOP, "Test Vault"),
        "mossSecret": hashtag_secret("#moss"),
        "articleSHA256": hashlib.sha256(ARTICLE).digest(),
    }
    lines = [
        "// Generated by tools/make_ios_vectors.py from the Python MOSS. Don't edit by hand:",
        "// re-run the script when the wire format changes.",
        "",
        "import Foundation",
        "",
        "enum TestVectors {",
        f"    static let rid: UInt16 = 0x{RID:04X}",
        f"    static let paddingByte: UInt8 = 0x{PADDING_BYTE:02X}",
        f"    static let title = {swift_string(TITLE)}",
        f"    static let vaultName = \"Test Vault\"",
        f"    static let fingerprint = \"{vault.fingerprint}\"",
        f"    static let errorText = \"no such article: Slow sand filtre\"",
        f"    static let articleLength = {len(ARTICLE)}",
        f"    static let articleStart = {swift_string(ARTICLE[:18].decode())}",
        f"    static let helloVersion = {swift_string(S.hello_version(hello)[0])}",
        f"    static let helloProtocol = {S.hello_version(hello)[1]}",
    ]
    for key, value in v.items():
        if isinstance(value, list):
            items = ",\n        ".join(f'Data(hex: "{c.hex()}")' for c in value)
            lines.append(f"    static let {key}: [Data] = [\n        {items},\n    ]")
        else:
            lines.append(f'    static let {key} = Data(hex: "{value.hex()}")')
    lines.append("}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(chunks)} spores, fingerprint {vault.fingerprint}")


def swift_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


if __name__ == "__main__":
    main()
